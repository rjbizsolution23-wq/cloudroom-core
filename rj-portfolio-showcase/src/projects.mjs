/**
 * Deterministic Zero-Duplicate Enforcer
 * Guarantees that no two projects share the same id, normalized liveUrl, or normalized title.
 */
export function getDeduplicatedProjects() {
  const seenIds = new Set();
  const seenUrls = new Set();
  const seenTitles = new Set();
  const clean = [];

  for (const proj of RAW_PROJECTS) {
    const normId = String(proj.id || "").trim().toLowerCase();
    const normUrl = String(proj.liveUrl || "")
      .trim()
      .toLowerCase()
      .replace(/\/+$/, "");
    const normTitle = String(proj.title || "").trim().toLowerCase();

    if (!normId || !normUrl || !normTitle) continue;
    if (seenIds.has(normId) || seenUrls.has(normUrl) || seenTitles.has(normTitle)) {
      continue;
    }
    seenIds.add(normId);
    seenUrls.add(normUrl);
    seenTitles.add(normTitle);
    clean.push({
      ...proj,
      number: clean.length + 1
    });
  }
  return clean;
}
